"""Build every blueprint folder: (re)generate, validate, render previews, refresh READMEs and the catalog.

    python3 tools/build.py                 # all blueprints: validate + previews + README auto sections + catalog
    python3 tools/build.py rail-buffer-station refined-concrete-60   # only these
    python3 tools/build.py --regen         # run each generate.py first (skips ones whose third_party input is missing)
    python3 tools/build.py --no-images     # skip PNG rendering (fast; CI uses this + git diff)
    python3 tools/build.py --renderer schematic   # simple coloured-box previews instead of game sprites

Images are rendered with real game sprites through Factorio Blueprint Editor (tools/render_fbe.py,
needs Playwright + Chromium: pip install -r tools/requirements.txt && python3 -m playwright install chromium).
If that is unavailable the schematic renderer (tools/render_preview.py) is used.

Per-blueprint layout (see blueprints/README.md):
    blueprints/<id>/meta.json        hand-written metadata (titles, summaries, outputs, variants, images…)
    blueprints/<id>/generate.py      optional generator that writes blueprint.txt (+ variants/*.txt)
    blueprints/<id>/blueprint.txt    the blueprint string
    blueprints/<id>/README.md        Korean doc; text between AUTO markers is rewritten by this tool
    blueprints/<id>/README.en.md     English doc, same rule
    blueprints/<id>/images/          preview.webp / detail.webp (generated) + attached screenshots
"""
